#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# wallpaper — pick, apply and restore a wallpaper on Hyprland.
#
# Wallpapers are user data, so Archway never ships or deletes any. It reads the
# folders below, keeps the last choice in ~/.local/state/archway/wallpaper and
# restores it at session start. hyprpaper does the drawing.
set -Eeuo pipefail

DRY_RUN=0
JSON=0
ROFI=0
MODE='list'

DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/archway/wallpapers"
PICTURES_DIR="${XDG_PICTURES_DIR:-$HOME/Pictures}/Wallpapers"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/archway"
STATE_FILE="$STATE_DIR/wallpaper"
# hyprpaper 0.8 replaced the request/response socket hyprctl used to speak with a
# framed HyprWire protocol, so `hyprctl hyprpaper ...` answers "invalid hyprpaper
# request" and every apply silently failed. hyprpaper still reads its own config
# file at startup, so the portable path is: write the config, restart the daemon.
# It owns no state beyond the wallpaper, so a restart is instant and safe.
HYPRPAPER_CONF="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/hyprpaper.conf"
HYPRPAPER_LOG="$STATE_DIR/hyprpaper.log"

usage() {
  cat << 'EOF'
wallpaper — Wayland wallpaper picker (hyprpaper)

Usage:
  wallpaper.sh [list] [--json]
  wallpaper.sh --rofi             # pick from a list (bound to Super+Alt+W)
  wallpaper.sh --set <file>
  wallpaper.sh --restore          # apply the last choice (session start)

Directories: ~/.local/share/archway/wallpapers and ~/Pictures/Wallpapers.
Supported: jpg, jpeg, png, webp.

hyprpaper 0.8 dropped the hyprctl IPC, so applying writes
~/.config/hypr/hyprpaper.conf and restarts the daemon (it holds no state).
EOF
}

die() {
  printf 'wallpaper: %s\n' "$1" >&2
  notify "wallpaper" "$1" || true
  exit "${2:-1}"
}

notify() {
  command -v notify-send > /dev/null 2>&1 && notify-send -a Archway "$@" > /dev/null 2>&1 || true
}

have() { command -v "$1" > /dev/null 2>&1; }

is_image() {
  local file=${1,,}
  case $file in
    *.jpg | *.jpeg | *.png | *.webp) return 0 ;;
    *) return 1 ;;
  esac
}

# One path per line, de-duplicated, stable order. Symlinks are skipped so a
# dangling link cannot make the picker offer an unusable entry.
wp_list() {
  local dir
  for dir in "$DATA_DIR" "$PICTURES_DIR"; do
    [[ -d $dir ]] || continue
    find "$dir" -maxdepth 2 -type f ! -type l 2> /dev/null | while IFS= read -r f; do
      is_image "$f" && printf '%s\n' "$f"
    done
  done | sort -u
}

wp_running() { pgrep -x hyprpaper > /dev/null 2>&1; }

wp_show() {
  local path=$1
  [[ -f $path ]] || die "not a file: $path"
  [[ -L $path ]] && die "refusing to follow a symlink: $path"
  is_image "$path" || die "unsupported image type: $path"

  if ((DRY_RUN)); then
    printf '[dry-run] hyprctl hyprpaper wallpaper ",%s"\n' "$path"
    printf '[dry-run] persist in %s\n' "$HYPRPAPER_CONF"
    return 0
  fi

  have hyprpaper || die "hyprpaper is not installed (pacman -S hyprpaper)" 3
  wp_write_conf "$path"
  wp_apply "$path" || die "hyprpaper did not apply $path (see $HYPRPAPER_LOG)"

  mkdir -p -- "$STATE_DIR"
  printf '%s\n' "$path" > "$STATE_FILE"
  chmod 644 -- "$STATE_FILE"
  notify "wallpaper" "$(basename -- "$path")"
}

# hyprpaper 0.8 reads anonymous blocks, not `wallpaper = monitor,path`:
#   wallpaper {
#       monitor =
#       path = /absolute/path
#       fit_mode = cover
#   }
# An empty monitor is the fallback for every output, which is what Archway
# wants (`archway applet wallpaper` is not per-monitor yet).
wp_write_conf() {
  local path=$1
  mkdir -p -- "$(dirname -- "$HYPRPAPER_CONF")"
  {
    printf '# Generated by archway (wallpaper applet); do not edit.\n'
    printf 'wallpaper {\n'
    printf '    monitor =\n'
    printf '    path = %s\n' "$path"
    printf '    fit_mode = cover\n'
    printf '}\n'
  } > "$HYPRPAPER_CONF.tmp"
  mv -f -- "$HYPRPAPER_CONF.tmp" "$HYPRPAPER_CONF"
  chmod 644 -- "$HYPRPAPER_CONF"
}

# Apply now, without a restart: in 0.8 only `wallpaper` and `listactive` survive
# on the hyprctl IPC (preload/unload/reload answer "invalid request"). The image
# is loaded on demand, and `listactive` is the confirmation that a monitor is
# actually showing it.
wp_ipc() {
  local path=$1
  have hyprctl || return 1
  [[ -n ${HYPRLAND_INSTANCE_SIGNATURE:-} ]] || return 1
  wp_running || return 1
  timeout 10 hyprctl hyprpaper wallpaper ",$path" > /dev/null 2>&1 || return 1
  timeout 5 hyprctl hyprpaper listactive 2> /dev/null | grep -qF "$path" || return 1
  return 0
}

# Fallback (headless apply, daemon down): start hyprpaper on the config written
# above. It owns no other state, so a restart is instant and safe.
wp_restart() {
  local i
  if wp_running; then
    pkill -x hyprpaper || true
    for ((i = 0; i < 20; i++)); do
      wp_running || break
      sleep 0.1
    done
  fi
  mkdir -p -- "$STATE_DIR"
  : > "$HYPRPAPER_LOG"
  # stdin and the usual inherited descriptors are closed: a daemon that keeps
  # them open holds the caller's pipe (a test runner, an ssh session, a script
  # pipeline) and that caller never sees EOF.
  setsid hyprpaper < /dev/null > "$HYPRPAPER_LOG" 2>&1 3>&- 4>&- 5>&- 6>&- 7>&- 8>&- 9>&- &
  for ((i = 0; i < 30; i++)); do
    wp_running && return 0
    sleep 0.1
  done
  return 1
}

wp_apply() {
  local path=$1
  wp_ipc "$path" && return 0
  wp_restart || return 1
  # After a cold start the config is what applies it; confirm on the daemon.
  have hyprctl && [[ -n ${HYPRLAND_INSTANCE_SIGNATURE:-} ]] || return 0
  timeout 5 hyprctl hyprpaper listactive 2> /dev/null | grep -qF "$path"
}

# At session start hyprpaper already read the config written by the last apply,
# so restore only has to re-apply when nothing is active (for example the image
# moved or the config was dropped).
wp_restore() {
  [[ -r $STATE_FILE ]] || return 0
  local path
  path=$(head -n1 "$STATE_FILE")
  [[ -n $path && -f $path ]] || return 0
  wp_running || return 0
  if have hyprctl && [[ -n ${HYPRLAND_INSTANCE_SIGNATURE:-} ]] &&
    timeout 5 hyprctl hyprpaper listactive 2> /dev/null | grep -qF "$path"; then
    return 0
  fi
  wp_write_conf "$path"
  wp_apply "$path" || return 0
}

wp_json() {
  local path sep=''
  printf '['
  while IFS= read -r path; do
    printf '%s%s' "$sep" "$(json_quote "$path")"
    sep=','
  done < <(wp_list)
  printf ']\n'
}

json_quote() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '"%s"' "$s"
}

wp_rofi() {
  have rofi || die "rofi is required for the picker" 3
  local entries=''
  entries=$(wp_list)
  if [[ -z $entries ]]; then
    die "no wallpapers found — drop images in $DATA_DIR or $PICTURES_DIR"
  fi
  local rows choice path
  rows=$(
    while IFS= read -r path; do
      printf '%s\t%s\n' "$(basename -- "$path")" "$path"
    done <<< "$entries"
  )
  # -format s returns the whole selected row, so the path comes back intact
  # even when two files share a name in different folders.
  choice=$(printf '%s\n' "$rows" |
    rofi -dmenu -i -p wallpaper -display-columns 1 -format s \
      -theme "$HOME/.config/archway/theme.d/rofi.rasi") || return 1
  [[ -n $choice ]] || return 1
  path=${choice#*$'\t'}
  wp_show "$path"
}

main() {
  local set_path=''
  while (($#)); do
    case $1 in
      --help | -h)
        usage
        exit 0
        ;;
      --dry-run) DRY_RUN=1 ;;
      --json) JSON=1 ;;
      --rofi) ROFI=1 ;;
      --restore) MODE=restore ;;
      --set)
        MODE='set'
        set_path=${2:-}
        [[ -n $set_path ]] || die "--set needs a file path" 2
        shift
        ;;
      list) MODE=list ;;
      -*)
        usage >&2
        die "unknown option: $1" 2
        ;;
      *) die "unexpected argument: $1" 2 ;;
    esac
    shift
  done

  case $MODE in
    restore) wp_restore ;;
    set) wp_show "$set_path" ;;
    list)
      if ((JSON)); then
        wp_json
      elif ((ROFI)); then
        wp_rofi
      else
        local count=0 path
        while IFS= read -r path; do
          printf '%s\n' "$path"
          count=$((count + 1))
        done < <(wp_list)
        ((count)) || printf 'no wallpapers in %s or %s\n' "$DATA_DIR" "$PICTURES_DIR" >&2
      fi
      ;;
  esac
}

main "$@"
