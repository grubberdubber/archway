#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# keys.sh — parse keybinds.toml, validate, generate sxhkdrc and the cheatsheet.
# shellcheck shell=bash

if [[ -n ${ARCHWAY_KEYS_LOADED:-} ]]; then return 0; fi
ARCHWAY_KEYS_LOADED=1

KEYBINDS_FILE="$ARCHWAY_ROOT/keybinds/keybinds.toml"
SXHKDRC_TARGET="$ARCHWAY_ROOT/dotfiles/dot_config/sxhkd/sxhkdrc"
KEYDOC_TARGET="$ARCHWAY_ROOT/docs/keybinds.md"

declare -ga K_ID=() K_KEYS=() K_CMD=() K_CAT=() K_DESC=()

keys_parse() {
  local file=${1:-$KEYBINDS_FILE}
  [[ -r $file ]] || die "keybinds file not found: $file" "$EX_PREFLIGHT"

  K_ID=() K_KEYS=() K_CMD=() K_CAT=() K_DESC=()
  local line key val idx=-1
  while IFS= read -r line || [[ -n $line ]]; do
    [[ $line =~ ^[[:space:]]*# ]] && continue
    line=$(trim "$line")
    [[ -z $line ]] && continue

    if [[ $line == '[[keybind]]' ]]; then
      idx=$((idx + 1))
      K_ID[idx]='' K_KEYS[idx]='' K_CMD[idx]='' K_CAT[idx]='' K_DESC[idx]=''
      continue
    fi
    ((idx < 0)) && continue

    if [[ $line =~ ^([a-z_]+)[[:space:]]*=[[:space:]]*\"(.*)\"$ ]]; then
      key=${BASH_REMATCH[1]}
      val=${BASH_REMATCH[2]}
    else
      die "malformed line in $file: $line" "$EX_PREFLIGHT"
    fi

    case $key in
      id) K_ID[idx]=$val ;;
      keys) K_KEYS[idx]=$val ;;
      command) K_CMD[idx]=$val ;;
      category) K_CAT[idx]=$val ;;
      description) K_DESC[idx]=$val ;;
      *) warn "unknown key in $file: $key" ;;
    esac
  done < "$file"

  ((${#K_ID[@]})) || die "no keybinds parsed from $file" "$EX_PREFLIGHT"
}

# Normalise a chord for duplicate detection: lowercase, alias ctrl->control,
# tokens trimmed and sorted (order of modifiers is irrelevant to sxhkd).
keys_normalize() {
  local chord=$1 token
  local -a tokens=()
  IFS='+' read -r -a tokens <<< "${chord,,}"
  local -a out=()
  for token in "${tokens[@]}"; do
    token=$(trim "$token")
    [[ -z $token ]] && continue
    case $token in
      ctrl | control) token=ctrl ;;
      super | mod4 | win) token=super ;;
      alt | mod1) token=alt ;;
      shift) token='shift' ;;
    esac
    out+=("$token")
  done
  printf '%s' "$(printf '%s\n' "${out[@]}" | sort | paste -sd+ -)"
}

# Combinations we refuse to bind: they belong to the kernel/firmware.
# Modifier order is irrelevant, so match tokens rather than a sorted string.
keys_is_reserved() {
  local chord=${1,,}
  if [[ $chord =~ (^|\+)[[:space:]]*(ctrl|control)[[:space:]]*(\+|$) ]] &&
    [[ $chord =~ (^|\+)[[:space:]]*alt[[:space:]]*(\+|$) ]]; then
    if [[ $chord =~ (^|\+)[[:space:]]*f([1-9]|1[0-2])[[:space:]]*(\+|$) ]]; then
      return 0
    fi
  fi
  [[ $chord == *sysrq* ]] && return 0
  return 1
}

keys_validate() {
  local errors=() i norm
  local -A seen=()

  keys_parse
  for i in "${!K_ID[@]}"; do
    [[ -n ${K_ID[i]} ]] || errors+=("entry #$((i + 1)) has no id")
    [[ -n ${K_KEYS[i]} ]] || errors+=("${K_ID[i]:-entry #$((i + 1))}: empty keys")
    [[ -n ${K_CMD[i]} ]] || errors+=("${K_ID[i]:-entry #$((i + 1))}: empty command")
    [[ -n ${K_CAT[i]} ]] || errors+=("${K_ID[i]:-entry #$((i + 1))}: empty category")

    [[ -z ${K_KEYS[i]} ]] && continue
    if keys_is_reserved "${K_KEYS[i]}"; then
      errors+=("${K_ID[i]}: '${K_KEYS[i]}' is reserved by the kernel/firmware")
    fi
    norm=$(keys_normalize "${K_KEYS[i]}")
    if [[ -n ${seen[$norm]:-} ]]; then
      errors+=("duplicate chord '${K_KEYS[i]}' in '${K_ID[i]}' and '${seen[$norm]}'")
    else
      seen[$norm]=${K_ID[i]}
    fi
  done

  local -A ids=()
  for i in "${!K_ID[@]}"; do
    [[ -z ${K_ID[i]} ]] && continue
    if [[ -n ${ids[${K_ID[i]}]:-} ]]; then
      errors+=("duplicate id: ${K_ID[i]}")
    fi
    ids[${K_ID[i]}]=1
  done

  if ((JSON_OUT)); then
    local sep='' e
    printf '{"binds":%d,"ok":%s,"errors":[' "${#K_ID[@]}" \
      "$([[ ${#errors[@]} -eq 0 ]] && echo true || echo false)"
    for e in "${errors[@]}"; do
      printf '%s%s' "$sep" "$(json_str "$e")"
      sep=','
    done
    printf ']}\n'
  else
    local e
    for e in "${errors[@]}"; do err "$e"; done
    ((${#errors[@]} == 0)) && ok "keybinds OK (${#K_ID[@]} binds)"
  fi
  if ((${#errors[@]} == 0)); then
    return 0
  fi
  return 1
}

keys_generate_sxhkdrc() {
  local target=${1:-$SXHKDRC_TARGET}
  {
    printf '# Generated by archway from keybinds/keybinds.toml. Do not edit.\n'
    printf '# Regenerate: archway keys generate\n\n'
    local cat i
    local -a cats=()
    while IFS= read -r cat; do cats+=("$cat"); done < <(
      for i in "${!K_CAT[@]}"; do printf '%s\n' "${K_CAT[i]}"; done | awk '!seen[$0]++'
    )
    for cat in "${cats[@]}"; do
      printf '# --- %s ---\n\n' "$cat"
      for i in "${!K_ID[@]}"; do
        [[ ${K_CAT[i]} == "$cat" ]] || continue
        printf '%s\n' "${K_KEYS[i]}"
        printf '\t%s\n\n' "${K_CMD[i]}"
      done
    done
  } > "$target.tmp"
  if ((DRY_RUN)); then
    ui_note "[dry-run] would write $target"
    rm -f -- "$target.tmp"
    return 0
  fi
  mv -f -- "$target.tmp" "$target"
  ok "sxhkdrc written: $target"
}

keys_generate_doc() {
  local target=${1:-$KEYDOC_TARGET}
  mkdir -p -- "$(dirname -- "$target")"
  # shellcheck disable=SC2016 # markdown, not shell expansion
  {
    printf '# Keybinds\n\n'
    printf '<!-- Generated by `archway keys generate` from `keybinds/keybinds.toml`. Do not edit. -->\n\n'
    printf 'Press `Super + /` at any time to open this list in a floating terminal.\n\n'
    local cat i
    local -a cats=()
    while IFS= read -r cat; do cats+=("$cat"); done < <(
      for i in "${!K_CAT[@]}"; do printf '%s\n' "${K_CAT[i]}"; done | awk '!seen[$0]++'
    )
    for cat in "${cats[@]}"; do
      printf '## %s\n\n' "$(printf '%s' "$cat" | awk '{print toupper(substr($0,1,1)) substr($0,2)}')"
      printf '| Key | Action | Command |\n|---|---|---|\n'
      for i in "${!K_ID[@]}"; do
        [[ ${K_CAT[i]} == "$cat" ]] || continue
        printf '| `%s` | %s | `%s` |\n' "${K_KEYS[i]}" "${K_DESC[i]}" "${K_CMD[i]//|/\\|}"
      done
      printf '\n'
    done
  } > "$target.tmp"

  if ((DRY_RUN)); then
    ui_note "[dry-run] would write $target"
    rm -f -- "$target.tmp"
    return 0
  fi
  mv -f -- "$target.tmp" "$target"
  ok "cheatsheet written: $target"
}

keys_generate() {
  keys_validate || die "refusing to generate from invalid keybinds" "$EX_FAIL"
  mkdir -p -- "$(dirname -- "$SXHKDRC_TARGET")"
  keys_generate_sxhkdrc "$SXHKDRC_TARGET"
  keys_generate_doc "$KEYDOC_TARGET"
}

# Ensure the committed artifacts match the source (used by CI and `keys check`).
keys_check() {
  keys_parse
  local tmp rc=0
  tmp=$(mktemp -d)
  keys_generate_sxhkdrc "$tmp/sxhkdrc" > /dev/null 2>&1 || true
  keys_generate_doc "$tmp/keybinds.md" > /dev/null 2>&1 || true
  if ! diff -q "$tmp/sxhkdrc" "$SXHKDRC_TARGET" > /dev/null 2>&1; then
    err "sxhkdrc is out of date; run 'archway keys generate'"
    rc=1
  fi
  if ! diff -q "$tmp/keybinds.md" "$KEYDOC_TARGET" > /dev/null 2>&1; then
    err "docs/keybinds.md is out of date; run 'archway keys generate'"
    rc=1
  fi
  rm -rf -- "$tmp"
  ((rc == 0)) && ok "generated keybind artifacts are up to date"
  return "$rc"
}

keys_list() {
  keys_parse
  if ((JSON_OUT)); then
    local i sep=''
    printf '['
    for i in "${!K_ID[@]}"; do
      printf '%s{"id":%s,"keys":%s,"command":%s,"category":%s,"description":%s}' \
        "$sep" "$(json_str "${K_ID[i]}")" "$(json_str "${K_KEYS[i]}")" \
        "$(json_str "${K_CMD[i]}")" "$(json_str "${K_CAT[i]}")" "$(json_str "${K_DESC[i]}")"
      sep=','
    done
    printf ']\n'
    return 0
  fi
  printf '%-28s %-34s %s\n' 'KEYS' 'ACTION' 'CATEGORY'
  local i
  for i in "${!K_ID[@]}"; do
    printf '%-28s %-34s %s\n' "${K_KEYS[i]}" "${K_DESC[i]}" "${K_CAT[i]}"
  done
}

keys_search() {
  local pattern=$1 i found=0
  keys_parse
  for i in "${!K_ID[@]}"; do
    if [[ ${K_KEYS[i]}${K_DESC[i]}${K_CMD[i]}${K_CAT[i]} == *"$pattern"* ]]; then
      printf '%-28s %-34s %s\n' "${K_KEYS[i]}" "${K_DESC[i]}" "${K_CMD[i]}"
      found=1
    fi
  done
  ((found)) || {
    warn "no keybind matches '$pattern'"
    return 1
  }
}
